'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const http=require('node:http');
const {createBridge,words}=require('./bridge.cjs');
test('owner bridge: authorization, paths, imports, uploads, optimistic saves and configuration',async()=>{
  const temp=await fs.mkdtemp(path.join(os.tmpdir(),'shamot-bridge-test-'));
  const root=path.join(temp,'site'),outside=path.join(temp,'outside');
  await fs.mkdir(path.join(root,'source/_posts'),{recursive:true});await fs.mkdir(outside);
  await fs.writeFile(path.join(outside,'article.md'),'# An imported article\n\nText and ![media](image.png)');
  await fs.writeFile(path.join(root,'_config.yml'),'title: shamot\n');
  await fs.writeFile(path.join(root,'_config.stellar.yml'),'leftbar:\n  brand:\n    tagline: Original\n');
  await fs.writeFile(path.join(outside,'secret.txt'),'external-secret');
  const bridge=createBridge({root,port:4317});
  await new Promise(resolve=>bridge.server.listen(0,'127.0.0.1',resolve));
  const url='http://127.0.0.1:'+bridge.server.address().port;
  let token;const origin='https://chadoshamot.github.io';
  const request=(route,body,extra={})=>fetch(url+route,{method:body?'POST':'GET',headers:{Origin:origin,...(token?{Authorization:'Bearer '+token}:{}),...(body?{'Content-Type':'application/json'}:{}),...extra},...(body?{body:JSON.stringify(body)}:{})});
  const command=async line=>{const res=await request('/api/command',{command:line});assert.equal(res.status,200);return (await res.text()).trim().split('\n').map(JSON.parse);};
  const success=events=>assert.equal(events.at(-1).ok,true,JSON.stringify(events));
  const failure=events=>assert.equal(events.at(-1).ok,false);
  try{
    assert.equal((await request('/api/command',{command:'pwd'})).status,401);
    assert.equal((await request('/api/pair',{code:'incorrect'})).status,403);
    assert.equal((await fetch(url+'/pair',{headers:{Origin:origin}})).status,403);
    const invalidHost=await new Promise((resolve,reject)=>{const req=http.get(url+'/pair',{headers:{Host:'attacker.example'}},res=>{res.resume();resolve(res.statusCode);});req.on('error',reject);});
    assert.equal(invalidHost,403);
    assert.equal((await fetch(url+'/api/pair',{method:'OPTIONS',headers:{Origin:'https://attacker.example'}})).status,403);
    const preflight=await fetch(url+'/api/pair',{method:'OPTIONS',headers:{Origin:origin,'Access-Control-Request-Private-Network':'true'}});
    assert.equal(preflight.status,204);assert.equal(preflight.headers.get('access-control-allow-private-network'),'true');
    const page=await (await fetch(url+'/pair')).text();const code=page.match(/connect http:\/\/[^ ]+ ([a-f0-9]{36})/)[1];
    const pair=await request('/api/pair',{code});assert.equal(pair.status,200);token=(await pair.json()).token;
    assert.equal((await request('/api/pair',{code})).status,403,'pair code must rotate');
    assert.equal((await request('/api/command',{command:'pwd'},{Origin:'https://attacker.example'})).status,403);
    failure(await command(`read "${path.join(outside,'secret.txt')}"`));
    failure(await command('read .shamot/bridge.json'));
    failure(await command('config set site __proto__.polluted yes'));assert.equal({}.polluted,undefined);
    failure(await command('config set site token x'));
    success(await command(`mount graduate "${outside}"`));
    success(await command('import @graduate/article.md first-post --category "技术"'));
    const post=await fs.readFile(path.join(root,'source/_posts/first-post.md'),'utf8');assert.match(post,/title: An imported article/);assert.match(post,/技术/);assert.match(post,/image\.png/);
    failure(await command('import @graduate/article.md first-post'));
    success(await command('new second-post --title "Another title" --category "学习"'));
    const edited=(await command('edit @site/source/_posts/first-post.md')).find(e=>e.type==='editor');
    let saved=await request('/api/save',{path:edited.path,hash:edited.hash,text:post+'\nUpdated'});assert.equal(saved.status,200);
    saved=await request('/api/save',{path:edited.path,hash:edited.hash,text:'stale overwrite'});assert.equal(saved.status,400);
    assert.match(await fs.readFile(edited.path,'utf8'),/Updated$/);
    success(await command('config set theme leftbar.brand.tagline "A personal signature"'));
    const resources=await command('resources');success(resources);assert(resources.some(e=>e.text?.includes(path.join(root,'source/_posts'))));
    success(await command('cat @site/_config.yml'));
    success(await command('harness access full'));assert.match(await fs.readFile(path.join(root,'.shamot/bridge.json'),'utf8'),/"harnessAccess": "full"/);
    failure(await command('harness access unknown'));
    assert.match(await fs.readFile(path.join(root,'_config.stellar.yml'),'utf8'),/A personal signature/);
    const upload=await fetch(url+'/api/upload',{method:'POST',headers:{Origin:origin,Authorization:'Bearer '+token,'X-Shamot-Path':encodeURIComponent('source/assets/uploads/photo.png')},body:Buffer.from([137,80,78,71])});assert.equal(upload.status,200);
    const traversal=await fetch(url+'/api/upload',{method:'POST',headers:{Origin:origin,Authorization:'Bearer '+token,'X-Shamot-Path':encodeURIComponent('source/../../escaped.txt')},body:'bad'});assert.equal(traversal.status,400);
    const privateUpload=await fetch(url+'/api/upload',{method:'POST',headers:{Origin:origin,Authorization:'Bearer '+token,'X-Shamot-Path':encodeURIComponent('source/.env')},body:'secret'});assert.equal(privateUpload.status,400);
    const download=await request('/api/download?path='+encodeURIComponent('@site/source/assets/uploads/photo.png'));assert.equal(download.status,200);assert.deepEqual(Buffer.from(await download.arrayBuffer()),Buffer.from([137,80,78,71]));
    await fs.symlink(outside,path.join(root,'source/escape'),process.platform==='win32'?'junction':'dir');failure(await command('read @site/source/escape/secret.txt'));
    failure(await command(`mount private "${path.join(root,'.shamot')}"`));
    failure(await command('remove @site --confirm'));
    success(await command('remove @site/source/_posts/second-post.md --confirm'));assert.equal(await fs.stat(path.join(root,'source/_posts/second-post.md')).then(()=>true,()=>false),false);
    assert.equal((await fs.readdir(path.join(root,'.shamot/trash'))).length,1);
    assert.equal((await request('/api/disconnect',{})).status,200);
    assert.equal((await request('/api/command',{command:'pwd'})).status,401);
    assert.deepEqual(words('mount graduate "D:\\My Folder"'),['mount','graduate','D:\\My Folder']);
  }finally{await bridge.close();await fs.rm(temp,{recursive:true,force:true});}
});
